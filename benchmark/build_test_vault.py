def _apply_depth() -> None:
    DOCS.update({path: text.strip() + "\n" for path, text in EXTRA_DOCS.items()})
    for path, text in list(DOCS.items()):
        prefix = PREFIXES.get(path, "").strip()
        suffix = SUFFIXES.get(path, "").strip()
        if prefix:
            title, _, rest = text.partition("\n")
            text = title + "\n\n" + prefix + "\n\n" + rest.lstrip("\n")
        if suffix:
            text = text.rstrip() + "\n\n" + suffix + "\n"
        DOCS[path] = text


def main() -> None:
    _apply_depth()
    if ROOT.exists():
        shutil.rmtree(ROOT)
    for path, text in DOCS.items():
        file = ROOT / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(text, encoding="utf-8")
    files = sorted(ROOT.rglob("*.md"))
    total = 0
    tables = headings = 0
    print(f"{'lines':>5}  path")
    for file in files:
        text = file.read_text(encoding="utf-8")
        count = text.count("\n") + 1
        total += count
        tables += text.count("\n|")
        headings += sum(line.startswith("#") for line in text.splitlines())
        print(f"{count:5}  {file.relative_to(ROOT).as_posix()}")
    print(f"{len(files)} notes, {total} lines, {headings} headings, table_rows={tables}")


if __name__ == "__main__":
    main()
