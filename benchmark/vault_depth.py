"""Longer, trap-heavy sections for the benchmark vault.

Prefixes are inserted under the title so the real configuration falls past
the first 80-line page. Numbers in a prefix are rejected drafts, not the
main result.
"""

from __future__ import annotations


def _prefix(intro: str, qa: list[tuple[str, str]], traps: list[tuple[str, str, str]]) -> str:
    lines = [
        "## 表前问答",
        "",
        intro,
        "",
        "这一页可以出现已经被放弃的数字。主配置在后文，不在下面的否决表里。",
        "",
    ]
    for question, answer in qa:
        lines.extend([f"### {question}", "", answer, ""])
    lines.extend(
        [
            "## 已经否决的草稿",
            "",
            "下表是复盘时留下的废弃值。抄到答案里会被算错。",
            "",
            "| 草稿名 | 废弃值 | 否决原因 |",
            "| --- | --- | --- |",
        ]
    )
    for name, value, why in traps:
        lines.append(f"| {name} | {value} | {why} |")
    lines.extend(
        [
            "",
            "### 草稿不能覆盖正文",
            "",
            "若本页和后文的表冲突，以后文的表为准。本页的职责是记下为什么这些草稿被丢掉，不是宣布最终数字。",
            "",
            "检索时如果只读到这一页，应该继续往后翻，而不是用废弃值填空。",
            "",
        ]
    )
    return "\n".join(lines).strip() + "\n"


